# --------------------------------------------------------------------- install
class TestInstallJsonLogging:
    """install_json_logging 幂等装配 + root 不被重复挂 JSON handler。"""

    def test_install_idempotent_no_duplicate_json_handler(self) -> None:
        root = logging.getLogger()
        # 自包含: 先清掉其他测试(如 web_api lifespan 触发 app.py install_json_logging)
        # 残留在 root 上的 JSON handler, 避免计数污染(before 必须 == 0)。
        for h in list(root.handlers):
            if isinstance(h.formatter, JSONFormatter):
                root.removeHandler(h)
        before = [h for h in root.handlers if isinstance(h.formatter, JSONFormatter)]
        assert before == [], "清理后 root 不应残留 JSON handler"
        h1 = install_json_logging()
        h2 = install_json_logging()  # 二次调用不应再添加
        after = [h for h in root.handlers if isinstance(h.formatter, JSONFormatter)]
        assert len(after) - len(before) == 1
        # 幂等: 二次调用返回同一 handler(已存在则复用), 不重复添加
        assert h2 is h1
        # 清理: 移除本次测试新增的 handler
        root.removeHandler(h1)
